#ifndef CLIO_RUNTIME_INCLUDE_TASK_STAT_MODEL_H_
#define CLIO_RUNTIME_INCLUDE_TASK_STAT_MODEL_H_

#include <string>
#include <unordered_map>

#include "clio_runtime/types.h"

namespace clio::run {

/**
 * The learned coefficients for ONE method of a pool.
 *
 * Mirrors the four per-method vectors a Container keeps (method_model_,
 * method_mape_, method_model_wall_, method_mape_wall_) for a single method id.
 */
struct MethodStatWeights {
  float cpu_coef_ = 1.0f;   ///< predicted_cpu_us = cpu_coef_ * (compute + 1)
  float cpu_mape_ = 0.0f;   ///< EMA of |predicted - real| / real for CPU
  float wall_coef_ = 1.0f;  ///< predicted_wall_us = wall_coef_ * (wall + 1)
  float wall_mape_ = 0.0f;  ///< EMA of |predicted - real| / real for wall clock
};

/**
 * A name-keyed snapshot of a pool's task-stat model, as persisted to disk.
 *
 * Keyed by method NAME rather than method id on purpose: method ids are
 * positions in an autogenerated enum, so adding or reordering a chimod's
 * methods renumbers them. Restoring an id-keyed file after such a change would
 * silently graft one method's learned coefficient onto another and quietly
 * corrupt every scheduling decision that reads it. Names survive renumbering;
 * a method whose name is absent from the file simply keeps its seed value, and
 * a name in the file that the binary no longer defines is ignored.
 */
struct TaskStatModelSnapshot {
  std::string chimod_name_;  ///< ChiMod that owns the pool (provenance only)
  std::string pool_name_;    ///< Pool the model was learned on (provenance only)
  float learning_rate_ = 0.0f;  ///< SGD rate in force when saved (provenance)
  /** method name -> learned coefficients */
  std::unordered_map<std::string, MethodStatWeights> methods_;

  /** @return true if the snapshot carries no per-method weights. */
  bool Empty() const { return methods_.empty(); }

  /**
   * Write the snapshot to `path` as YAML, creating parent directories.
   * The write is atomic: it goes to `path`.tmp and is then renamed over
   * `path`, so a crash mid-save cannot leave a truncated file that the next
   * startup would load as authoritative.
   * @return true on success.
   */
  bool Save(const std::string &path) const;

  /**
   * Read a snapshot previously written by Save(). A missing file is NOT an
   * error condition worth logging loudly — it is the normal first-run case —
   * and returns false with the snapshot left empty.
   * @return true if the file existed and parsed.
   */
  bool Load(const std::string &path);
};

/**
 * Canonical on-disk location of a pool's persisted model:
 *   <conf_dir>/models/<chimod_name>.<pool_name>.<node_id>.yaml
 *
 * Per node, because the model is learned from one node's hardware — restoring
 * a fast node's coefficients onto a slow one would mispredict from the first
 * task. Characters that are not path-safe in the pool name are replaced with
 * '_' (CTE pool names are paths, e.g. "/mnt/hdd/cte").
 *
 * @return the full path, or an empty string if no ConfigManager is available.
 */
std::string TaskStatModelPath(const std::string &chimod_name,
                              const std::string &pool_name, u32 node_id);

}  // namespace clio::run

#endif  // CLIO_RUNTIME_INCLUDE_TASK_STAT_MODEL_H_
