def simple_fold(cp):
  """Simple case fold of one code point, or None when it has none."""
  c = chr(cp)
  full = c.casefold()
  if len(full) == 1:
    return ord(full) if full != c else None
  low = c.lower()
  if len(low) == 1 and low != c:
    return ord(low)
  return None


def main():
  pairs = []
  for cp in range(0x80, 0x110000):
    if 0xD800 <= cp <= 0xDFFF:
      continue  # surrogates are not encodable in UTF-8
    to = simple_fold(cp)
    if to is not None:
      pairs.append((cp, to))
  major, minor, update = (int(x) for x in unicodedata.unidata_version.split("."))
  version = (major << 16) | (minor << 8) | update
  out = sys.stdout
  out.write(HEADER % (unicodedata.unidata_version, version))
  for cp, to in pairs:
    out.write("    {0x%05X, 0x%05X},\n" % (cp, to))
  out.write(FOOTER)


if __name__ == "__main__":
  main()
