// Pool ids and codec wire ids, host-side. The DATA constants that decide the
// generated bytes now live in weights_math.h, shared with every substrate;
// what stays here is only what the DRIVER needs.
// THE COMPRESSOR IS OPTIONAL, and on the SYCL build it is absent: the GPU
// codec is nvcomp, which has no SYCL equivalent, so CLIO_CTE_ENABLE_COMPRESS
// is off there and the clio_cte_compressor module is not built. Composing a
// pool for a module that does not exist fails the whole runtime
// ("Failed to create pool cte_compressor ... return code: 22"), so the
// compose below and the vector's target pool both follow this flag.
//
// The RAW regime -- which is most of what this benchmark measures -- works
// either way. Only --compressed needs the module, and it says so.
#if defined(CLIO_CTE_HAVE_COMPRESSOR)
constexpr bool kHaveCompressor = true;
#else
constexpr bool kHaveCompressor = false;
#endif
const clio::run::PoolId kCompressorPool(512, 0);
// cte_core is 512.0 -- clio::cte::core::kCtePoolId, and what every generated
// cluster config declares (`pool_id: "512.0"`). This said (513, 0), which is
// not a pool at all: the tier bdevs take major 513 but with a PER-NODE minor
// (513.1, 513.2 for ram::gvw_ram_node0/node1), so 513.0 never exists.
//
// It survived because the only user that matters is the stored-footprint
// loop below, whose GetBlobSize failures are silently skipped
// (`if (rc == 0) stored += ...`) -- and because the Vector takes
// kCompressorPool, not this, whenever a compressor is built in. So the run
// still produced correct numbers and merely reported stored=0.
//
// Distributed, it stopped being cosmetic: routing to a pool with no local
// container returns RouteResult::Dne, and RouteTask then burns its FULL
// 5000 ms inline retry budget before failing -- once per page. At 2 nodes
// every weights cell in the cache sweep hit the 900 s cap having done no
// useful work, at every cache and block rung.
// THE CORE POOL'S ID DEPENDS ON WHICH CONFIG IS LIVE, and hardcoding either
// choice breaks the other mode -- both have now happened:
//
//   self-written config (single-node):  compressor 512.0 -> cte_core 513.0
//   cluster config (gvw_conf.yaml):     cte_core 512.0, no compressor
//
// (513, 0) broke distributed -- routing to a pool with no container burns the
// full 5000 ms inline retry per page (the previous fix's finding, which
// stands). kCtePoolId (512.0) broke the single-node NO-COMPRESSOR build: its
// puts went to a pool its own config declares as the COMPRESSOR slot, which
// does not exist there, and the seed failed every put (put_errors=32,
// "SEED DID NOT CONVERGE"). The CUDA build dodged that only because it
// routes via kCompressorPool -- the same 512.0, which under the CLUSTER
// config happens to alias cte_core.
//
// So the ids are chosen at runtime, from the same fact the config guard
// already keys on: whether CLIO_SERVER_CONF was supplied.
static clio::run::PoolId g_core_pool = clio::cte::core::kCtePoolId;
static clio::run::PoolId g_storage_pool = clio::cte::core::kCtePoolId;
constexpr int kLz4WireId = 4;      // registry: {"lz4", 4, ...}   CPU codec
// GPU codec. This is the one that matters here: decompressing on the device
// is impossible while a kernel spins on its fault, because the codec is itself
// a kernel and cannot launch behind a resident one. A yielding fault path is
// what makes it reachable at all.
constexpr int kNvcompLz4WireId = 11;  // registry: {"nvcomp-lz4", 11, ...}

clio::run::u64 NowMs() {
  return static_cast<clio::run::u64>(
      std::chrono::duration_cast<std::chrono::milliseconds>(
          std::chrono::steady_clock::now().time_since_epoch())
          .count());
}

