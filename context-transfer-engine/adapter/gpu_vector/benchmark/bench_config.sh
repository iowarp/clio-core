#!/usr/bin/env bash
# The ONE runtime configuration used by every gpu_vector benchmark launcher.
#
# Source this file and call bench_clio_yaml. Every knob that a scale run
# has needed lives here, once, so a launcher cannot forget one (the E4 batch
# script lacked neighborhood_size and failed at 64 nodes with rc=11 on
# nodes 0 and 32 while the E1 and E5 scripts had it).
#
#   bench_clio_yaml <out.yaml> <hostfile> [port]
#
# Environment (all optional):
#   BENCH_TIERS         storage tiers, one per line
#                       "path|bdev_type|capacity|score[|persistence_level]",
#                       e.g. "ram::gv_dram|ram|200000MB|0.5" or
#                       "/mnt/x/node__RANK__.dat|file|70000MB|0.5|long_term".
#                       Default: one 200000MB DRAM tier. A path may contain
#                       __RANK__ for the caller to substitute per rank.
#   BENCH_NEIGHBORHOOD  networking.neighborhood_size (default 1024). Must be >=
#                       the node count: a Broadcast wider than it is split into
#                       Range queries the receiver runs only locally.
#   BENCH_RT_THREADS    runtime.num_threads (default 8)
#   BENCH_QUEUE_DEPTH   runtime and gpu queue_depth (default 8192)
#   BENCH_PROGRESS_MS   runtime.task_progress_interval_ms (default 5000). It was
#                       turned off during the evaluation because the probe
#                       reported live replicas Gone on backlogged nodes; that is
#                       fixed (generations, two strikes), and with SWIM off the
#                       probe is also what notices a dead peer (three unanswered
#                       probes mark the node dead).
#   BENCH_DPE           cte_core dpe_type (default max_bw)
#
# SWIM is always off: its detector declares busy nodes dead in wide collectives.

bench_clio_yaml() {
  local out=$1 hostfile=$2 port=${3:-9460}
  local tiers=${BENCH_TIERS:-"ram::gv_dram|ram|200000MB|0.5"}
  local storage=""
  local line path bdev cap score plevel
  while IFS= read -r line; do
    [ -z "${line}" ] && continue
    IFS='|' read -r path bdev cap score plevel <<< "${line}"
    storage+="      - path: \"${path}\"
        bdev_type: \"${bdev}\"
"
    [ -n "${plevel}" ] && storage+="        persistence_level: \"${plevel}\"
"
    storage+="        capacity_limit: \"${cap}\"
        score: ${score}
"
  done <<< "${tiers}"
  cat > "${out}" <<EOF
# Generated by bench_config.sh; edit that file, not this one.
networking:
  port: ${port}
  hostfile: "${hostfile}"
  neighborhood_size: ${BENCH_NEIGHBORHOOD:-1024}

swim:
  enabled: false

runtime:
  num_threads: ${BENCH_RT_THREADS:-8}
  queue_depth: ${BENCH_QUEUE_DEPTH:-8192}
  first_busy_wait: 10000000
  task_progress_interval_ms: ${BENCH_PROGRESS_MS:-5000}

gpu:
  queue_depth: ${BENCH_QUEUE_DEPTH:-8192}

compose:
  - mod_name: clio_bdev
    pool_name: "ram::chi_default_bdev"
    pool_query: local
    pool_id: "301.0"
    bdev_type: ram
    capacity: "1GB"

  - mod_name: clio_cte_core
    pool_name: cte_core
    pool_query: local
    pool_id: "512.0"
    targets:
      neighborhood: 1
    storage:
${storage}    dpe:
      dpe_type: "${BENCH_DPE:-max_bw}"
EOF
}

# bench_check_binary <exe>
#
# Refuse a benchmark binary that is OLDER than a runtime or gpu_vector header.
# The benchmarks compile those headers (Host, task structs, the device
# vector) into themselves, so a header changed after the build leaves an old
# binary reading fields at stale offsets: it crashed inside main() ~7 s into
# every run and looked like a runtime bug for an hour. Headers, not the
# libraries: a relinked library with unchanged headers is harmless.
# BENCH_ALLOW_STALE=1 overrides.
bench_check_binary() {
  local exe=$1 root newer
  root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)
  # Module client headers count too; *_runtime.h files are server-side only.
  newer=$(find "${root}/context-runtime/include" "${root}/context-transport-primitives/include" \
               "${root}/context-runtime/modules"/*/include \
               "${root}/context-transfer-engine/core/include" \
               "${root}/context-transfer-engine/adapter/gpu_vector/include" \
               -name '*.h' ! -name '*_runtime.h' -newer "${exe}" -print -quit 2>/dev/null)
  if [ -n "${newer}" ]; then
    echo "STALE BINARY: ${exe} is older than ${newer}; rebuild it (BENCH_ALLOW_STALE=1 to run anyway)"
    [ "${BENCH_ALLOW_STALE:-0}" = 1 ] || return 1
  fi
  return 0
}

# bench_watch_ranks <rundir> <launcher pid> <nranks> [poll seconds]
#
# FAIL FAST. Each rank appends "rank N on <host> exit=<rc>" to rank<N>.log
# when it ends. One dead rank used to leave the others parked at ROUND CAP for
# the whole per-rank cap (20 minutes of 64 nodes to report a failure known
# after 30 seconds). Poll the logs; the first non-zero exit kills the
# launcher, which tears the remaining ranks down. Returns that rank's exit
# status, or the launcher's own when every rank ended cleanly.
bench_watch_ranks() {
  local rundir=$1 lpid=$2 nranks=$3 poll=${4:-5}
  local bad rc
  while kill -0 "${lpid}" 2>/dev/null; do
    bad=$(grep -lE '^rank [0-9]+ on .* exit=[1-9][0-9]*$' "${rundir}"/rank*.log 2>/dev/null | head -1)
    if [ -n "${bad}" ]; then
      rc=$(grep -oE 'exit=[0-9]+$' "${bad}" | tail -1 | cut -d= -f2)
      echo "FAILFAST: $(basename "${bad}" .log) exited ${rc}; stopping the other ranks"
      kill -TERM "${lpid}" 2>/dev/null
      sleep 5
      kill -KILL "${lpid}" 2>/dev/null
      wait "${lpid}" 2>/dev/null
      return "${rc}"
    fi
    sleep "${poll}"
  done
  wait "${lpid}"
}
