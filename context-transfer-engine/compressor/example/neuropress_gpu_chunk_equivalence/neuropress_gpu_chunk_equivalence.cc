/**
 * @file neuropress_gpu_chunk_equivalence.cc
 * @brief Runs native NeuroPress and Clio-NeuroPress over the SAME GPU-resident
 *        chunk and compares them callback by callback.
 *
 * WHAT THIS ANSWERS. Not "does the final compressed output match" -- that
 * question has been asked before and its answer is uninformative when it is
 * "no", because it does not say WHERE. This walks the pipeline stage by stage
 * from a chunk that is already in GPU memory and reports the FIRST callback at
 * which the two implementations stop agreeing, with the device pointers, the
 * hashes and a byte-level comparison at each step.
 *
 * THE INPUT IS GPU-RESIDENT FROM BIRTH. Each chunk is generated by a CUDA
 * kernel into a cudaMalloc'd buffer. There is no host original that was
 * uploaded; there is nothing to upload. The pointer is then classified through
 * cudaPointerGetAttributes and the run refuses to continue unless the driver
 * itself says DEVICE.
 *
 * BOTH SIDES SEE THE SAME BYTES. One buffer is generated and both
 * implementations read it. The harness additionally byte-compares the two
 * sides' views of the input, so "the inputs were equal" is measured rather
 * than assumed.
 *
 * Run:
 *   bin/neuropress_gpu_chunk_equivalence [--out DIR] [--no-e2e]
 *
 * Environment:
 *   NPEQ_OUT_DIR   where the trace and report files are written
 *   NPEQ_E2E       0 to skip the end-to-end production cross-check
 */

